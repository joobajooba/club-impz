local F = { height = 9, capHeight = 7 }

local function glyph(ch) return G[ch] or G[" "] end

-- width in output pixels of str drawn at scale s (bold adds one pixel)
function F.width(str, s, bold)
  local w = 0
  for i = 1, #str do w = w + (#glyph(str:sub(i, i))[1] + 1) * s end
  return math.max(0, w - s) + (bold and 1 or 0)
end

-- draws str with its cap top at (x, y); color is a pixel value from app.pixelColor
function F.draw(img, str, x, y, s, color, bold)
  for i = 1, #str do
    local g = glyph(str:sub(i, i))
    for row, line in ipairs(g) do
      for col = 1, #line do
        if line:sub(col, col) == "#" then
          for dy = 0, s - 1 do
            for dx = 0, s - 1 + (bold and 1 or 0) do
              img:drawPixel(x + (col - 1) * s + dx, y + (row - 1) * s + dy, color)
            end
          end
        end
      end
    end
    x = x + (#g[1] + 1) * s
  end
end

return F
